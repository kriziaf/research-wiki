#!/usr/bin/env node
// One-off manual snapshot of the wiki/ corpus into data/wiki-index.js for the
// MVP1 search/retrieve/view test. Not wired into any build step — rerun by
// hand (`node scripts/snapshot-wiki.mjs`) when the vault changes.
//
// Source: /Users/krizfernux/Obsidian Vault/ant-colony/wiki-site/wiki/
// See PHASE1_PLAN.md "MVP 1" section for why this is a manual snapshot
// rather than the repeatable export-script approach.

import fs from 'node:fs';
import path from 'node:path';

const VAULT_WIKI_ROOT = '/Users/krizfernux/Obsidian Vault/ant-colony/wiki-site/wiki';
const ZONES = ['concepts', 'entities', 'projects'];
const OUT_FILE = new URL('../data/wiki-index.js', import.meta.url);

function parseFrontmatter(raw) {
  const match = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/);
  if (!match) return { meta: {}, body: raw };
  const [, fmBlock, body] = match;
  const lines = fmBlock.split(/\r?\n/);
  const meta = {};
  let i = 0;
  while (i < lines.length) {
    const line = lines[i];
    const kv = line.match(/^([A-Za-z_][\w-]*):\s*(.*)$/);
    if (!kv) { i++; continue; }
    const [, key, rawValue] = kv;
    if (rawValue.trim() === '') {
      // possible block list on following indented "- " lines
      const items = [];
      let j = i + 1;
      while (j < lines.length && /^\s+-\s+/.test(lines[j])) {
        items.push(lines[j].replace(/^\s+-\s+/, '').trim().replace(/^"(.*)"$/, '$1'));
        j++;
      }
      meta[key] = items;
      i = j;
    } else if (/^\[.*\]$/.test(rawValue.trim())) {
      meta[key] = rawValue.trim().slice(1, -1).split(',')
        .map(s => s.trim().replace(/^"(.*)"$/, '$1')).filter(Boolean);
      i++;
    } else {
      meta[key] = rawValue.trim().replace(/^"(.*)"$/, '$1');
      i++;
    }
  }
  return { meta, body: body.trim() };
}

function slugify(zone, filename) {
  const base = filename.replace(/\.md$/, '');
  return `${zone}/${base}`.toLowerCase().replace(/\s+/g, '-');
}

const docs = [];
for (const zone of ZONES) {
  const dir = path.join(VAULT_WIKI_ROOT, zone);
  if (!fs.existsSync(dir)) continue;
  const files = fs.readdirSync(dir).filter(f => f.endsWith('.md'));
  for (const file of files) {
    const raw = fs.readFileSync(path.join(dir, file), 'utf8');
    const { meta, body } = parseFrontmatter(raw);
    docs.push({
      id: slugify(zone, file),
      title: meta.title || file.replace(/\.md$/, ''),
      type: meta.type || zone.slice(0, -1),
      tags: Array.isArray(meta.tags) ? meta.tags : (meta.tags ? [meta.tags] : []),
      created: meta.created || '',
      updated: meta.updated || '',
      body,
    });
  }
}

docs.sort((a, b) => a.title.localeCompare(b.title));

const out = `// AUTO-GENERATED by scripts/snapshot-wiki.mjs — manual snapshot, not live data.
// Regenerate: node scripts/snapshot-wiki.mjs
// Snapshotted: ${new Date().toISOString().slice(0, 10)} — ${docs.length} documents
window.WIKI_INDEX = ${JSON.stringify(docs, null, 2)};
`;

fs.writeFileSync(OUT_FILE, out);
console.log(`Wrote ${docs.length} documents to ${OUT_FILE.pathname}`);
for (const zone of ZONES) {
  console.log(`  ${zone}: ${docs.filter(d => d.id.startsWith(zone + '/')).length}`);
}
