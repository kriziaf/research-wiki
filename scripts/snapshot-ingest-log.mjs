#!/usr/bin/env node
// One-off manual snapshot of raw/clippings/ ingest activity into
// data/ingest-log.js, for the in-app "Ingest Log" page. Not wired into any
// build step — rerun by hand (`node scripts/snapshot-ingest-log.mjs`) after
// a wiki-ingest run.
//
// Source: <vaultRoot>/raw/clippings/ — vaultRoot comes from the gitignored
// .claude/wiki-ingest.local.json (see .claude/skills/wiki-ingest/SKILL.md),
// so no personal path is hardcoded in this committed script.

import fs from 'node:fs';
import path from 'node:path';

const CONFIG_FILE = new URL('../.claude/wiki-ingest.local.json', import.meta.url);
const FALLBACK_VAULT_ROOT = '/Users/krizfernux/Obsidian Vault/ant-colony/wiki-site';

function loadVaultRoot() {
  try {
    const config = JSON.parse(fs.readFileSync(CONFIG_FILE, 'utf8'));
    if (config.vaultRoot) return config.vaultRoot;
  } catch {
    // no local config yet — fall back below
  }
  console.warn(`No .claude/wiki-ingest.local.json found; falling back to ${FALLBACK_VAULT_ROOT}`);
  return FALLBACK_VAULT_ROOT;
}

const CLIPPINGS_DIR = path.join(loadVaultRoot(), 'raw', 'clippings');
const OUT_FILE = new URL('../data/ingest-log.js', import.meta.url);

function parseFrontmatter(raw) {
  const match = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/);
  if (!match) return {};
  const fmBlock = match[1];
  const lines = fmBlock.split(/\r?\n/);
  const meta = {};
  for (const line of lines) {
    const kv = line.match(/^([A-Za-z_][\w-]*):\s*(.*)$/);
    if (!kv) continue;
    const [, key, rawValue] = kv;
    if (rawValue.trim() !== '') {
      meta[key] = rawValue.trim().replace(/^"(.*)"$/, '$1');
    }
  }
  return meta;
}

const byDate = {};
if (fs.existsSync(CLIPPINGS_DIR)) {
  const files = fs.readdirSync(CLIPPINGS_DIR).filter(f => f.endsWith('.md'));
  for (const file of files) {
    const full = path.join(CLIPPINGS_DIR, file);
    const raw = fs.readFileSync(full, 'utf8');
    const meta = parseFrontmatter(raw);
    const title = meta.title || file.replace(/\.md$/, '');
    const date = meta.created || fs.statSync(full).mtime.toISOString().slice(0, 10);
    (byDate[date] = byDate[date] || []).push(title);
  }
}

const entries = Object.keys(byDate)
  .sort((a, b) => b.localeCompare(a))
  .map(date => ({ date, articles: byDate[date].sort((a, b) => a.localeCompare(b)) }));

const totalArticles = entries.reduce((n, e) => n + e.articles.length, 0);

const out = `// AUTO-GENERATED by scripts/snapshot-ingest-log.mjs — manual snapshot, not live data.
// Regenerate: node scripts/snapshot-ingest-log.mjs
// Snapshotted: ${new Date().toISOString().slice(0, 10)} — ${totalArticles} articles across ${entries.length} days
window.INGEST_LOG = ${JSON.stringify(entries, null, 2)};
`;

fs.writeFileSync(OUT_FILE, out);
console.log(`Wrote ${totalArticles} articles across ${entries.length} days to ${OUT_FILE.pathname}`);
